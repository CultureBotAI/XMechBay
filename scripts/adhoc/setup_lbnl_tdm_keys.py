import urllib.error
import urllib.parse
import urllib.request
from pathlib import Path

try:
    import requests as _requests
except ImportError:
    _requests = None  # type: ignore[assignment]

HOME = Path.home()
ENV_FILE = HOME / ".config" / "lbnl-tdm.env"
BACKUP_SUFFIX = ".bak-lbnl-tdm-20261108"

MARKER_START = "# >>> lbnl-tdm api keys >>>"
MARKER_END = "# <<< lbnl-tdm api keys <<<"
RC_BLOCK = f"""{MARKER_START}
if [ -f "$HOME/.config/lbnl-tdm.env" ]; then
  . "$HOME/.config/lbnl-tdm.env"
fi
{MARKER_END}"""

KEY_SPECS = [
    (
        "WILEY_TDM_TOKEN",
        "Wiley TDM Client Token (UUID)",
        "Also exported as TDM_API_TOKEN for wiley-tdm",
    ),
    (
        "SPRINGER_OPENACCESS_API_KEY",
        "Springer Nature Open Access API Key",
        "Also exported as SPRINGER_API_KEY for fulltext_access.py",
    ),
    (
        "SPRINGER_META_API_KEY",
        "Springer Nature Meta API Key",
        "Used for Springer Nature Meta v2 API queries",
    ),
    (
        "SPRINGER_LIFESCIENCE_API_KEY",
        "Springer Nature LifeScience Meta API Key",
        "Used for Springer Nature LifeScience Meta v2 queries (falls back to SPRINGER_META_API_KEY)",
    ),
    (
        "CORE_API_KEY",
        "CORE v3 API Key",
        "Used by fulltext_access.py try_core()",
    ),
    (
        "CAS_COMMON_CHEMISTRY_API_KEY",
        "CAS Common Chemistry API Key",
        "Also exported as CAS_API_KEY for CAS Common Chemistry REST API",
    ),
    (
        "ELSEVIER_API_KEY",
        "Elsevier ScienceDirect API Key (optional — Enter to skip)",
        "Used by fulltext_access.py try_elsevier_tdm()",
    ),
]


class _ExactHeader(str):
    """Preserve exact HTTP header casing through urllib.request's .capitalize() and .title() calls."""

    def capitalize(self) -> _ExactHeader:
        return self

    def title(self) -> _ExactHeader:
        return self


def _parse_env_file(path: Path) -> dict[str, str]:
    vals: dict[str, str] = {}
    if not path.is_file():
        return vals
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        m = re.match(r"^(?:export\s+)?([A-Z0-9_]+)=(.*)$", line)
        if not m:
            continue
        k, v = m.group(1), m.group(2).strip()
        if len(v) >= 2 and v[0] == v[-1] and v[0] in ('"', "'"):
            v = v[1:-1]
        if not v.startswith("$"):
            vals[k] = v
    return vals


def load_existing(path: Path) -> dict[str, str]:
    vals = _parse_env_file(path)
    bak_path = path.with_name(path.name + BACKUP_SUFFIX)
    bak_vals = _parse_env_file(bak_path)

    if not vals.get("CAS_COMMON_CHEMISTRY_API_KEY") and vals.get("CAS_API_KEY"):
        vals["CAS_COMMON_CHEMISTRY_API_KEY"] = vals["CAS_API_KEY"]

    if not vals.get("SPRINGER_LIFESCIENCE_API_KEY"):
        ls_fallback = (
            bak_vals.get("SPRINGER_LIFESCIENCE_API_KEY")
            or vals.get("SPRINGER_META_API_KEY", "")
        )
        if ls_fallback:
            vals["SPRINGER_LIFESCIENCE_API_KEY"] = ls_fallback
    return vals


def mask(val: str) -> str:
    if not val:
        return "(unset)"
    return f"set (len={len(val)})"


def backup_file(path: Path) -> Path | None:
    if not path.is_file():
        return None
    bak = path.with_name(path.name + BACKUP_SUFFIX)
    if not bak.exists():
        shutil.copy2(path, bak)
    return bak


def write_env_file(values: dict[str, str], zotero_dir: str) -> Path | None:
    ENV_FILE.parent.mkdir(parents=True, exist_ok=True)
    bak = backup_file(ENV_FILE)
    lines = [
        "# LBNL Library Services, Publisher TDM & CAS Common Chemistry API keys",
        "# Generated by XMechBay/scripts/adhoc/setup_lbnl_tdm_keys.py (mode 0600)",
        f'export ZOTERO_DATA_DIR="{zotero_dir}"',
    ]
    for env_name, _, _ in KEY_SPECS:
        val = values.get(env_name, "").strip()
        escaped = val.replace("\\", "\\\\").replace('"', '\\"')
        lines.append(f'export {env_name}="{escaped}"')

    lines += [
        "# Compatibility aliases for fulltext_access.py, springernature-api-client, wiley-tdm, and CAS:",
        'export SPRINGER_API_KEY="$SPRINGER_OPENACCESS_API_KEY"',
        'export SPRINGERNATURE_API_KEY="$SPRINGER_OPENACCESS_API_KEY"',
        'export TDM_API_TOKEN="$WILEY_TDM_TOKEN"',
        'export CAS_API_KEY="$CAS_COMMON_CHEMISTRY_API_KEY"',
        "",
    ]
    ENV_FILE.write_text("\n".join(lines), encoding="utf-8")
    os.chmod(ENV_FILE, 0o600)
    return bak


def ensure_rc_sourced(rc_path: Path, create_if_missing: bool = False) -> tuple[bool, Path | None]:
    if not rc_path.is_file():
        if not create_if_missing:
            return False, None
        rc_path.write_text(RC_BLOCK + "\n", encoding="utf-8")
        return True, None
    text = rc_path.read_text(encoding="utf-8")
    pattern = re.compile(
        re.escape(MARKER_START) + r"[\s\S]*?" + re.escape(MARKER_END)
    )
    if pattern.search(text):
        new_text = pattern.sub(lambda _: RC_BLOCK, text, count=1)
    else:
        new_text = text.rstrip("\n") + "\n\n" + RC_BLOCK + "\n"
    if new_text == text:
        return False, None
    bak = backup_file(rc_path)
    rc_path.write_text(new_text, encoding="utf-8")
    return True, bak


def sync_all_shell_rcs() -> None:
    # ~/.zshenv is sourced by ALL zsh invocations (including non-interactive
    # `zsh -c` subshells spawned by already-running Codex/Claude sessions on M5).
    for rc_name, create in ((".zshenv", True), (".zshrc", False), (".bashrc", False), (".bash_profile", False)):
        rc_path = HOME / rc_name
        changed, rc_bak = ensure_rc_sourced(rc_path, create_if_missing=create)
        if changed:
            undo_note = f" (undo: cp {rc_bak} {rc_path})" if rc_bak else f" (created {rc_path})"
            print(f"Updated {rc_path} to source {ENV_FILE}{undo_note}")
        elif rc_path.is_file():
            print(f"Verified {rc_path} already sources {ENV_FILE}")


def _probe(url: str, headers: dict[str, str] | None = None) -> tuple[bool, str]:
    req_headers = {"User-Agent": "CommunityMech-fulltext/1.0", **(headers or {})}
    if _requests is not None:
        try:
            with _requests.get(url, headers=req_headers, timeout=20, stream=True) as resp:
                chunk = next(resp.iter_content(chunk_size=4096), b"")
                if 200 <= resp.status_code < 300:
                    return True, f"HTTP {resp.status_code} ({len(chunk)} bytes read)"
                err_body = chunk.decode("utf-8", errors="ignore").strip()
                err_body = re.sub(r"api_key=[^&\s\"']+", "api_key=***", err_body)
                err_body = re.sub(r"\s+", " ", err_body)[:160]
                amzn_err = resp.headers.get("x-amzn-ErrorType") or resp.headers.get("WWW-Authenticate") or ""
                extra = f" [{amzn_err}]" if amzn_err else ""
                detail = f" — {err_body}" if err_body else ""
                return False, f"HTTP {resp.status_code} ({resp.reason}){extra}{detail}"
        except Exception as e:
            return False, f"{type(e).__name__}: {e}"

    exact_headers = {_ExactHeader(k): v for k, v in req_headers.items()}
    req = urllib.request.Request(url, headers=exact_headers)
    try:
        with urllib.request.urlopen(req, timeout=20) as resp:
            body = resp.read(4096)
            return True, f"HTTP {resp.status} ({len(body)} bytes read)"
    except urllib.error.HTTPError as e:
        detail = ""
        try:
            err_body = e.read(512).decode("utf-8", errors="ignore").strip()
            err_body = re.sub(r"api_key=[^&\s\"']+", "api_key=***", err_body)
            err_body = re.sub(r"\s+", " ", err_body)[:160]
            if err_body:
                detail = f" — {err_body}"
        except Exception:
            pass
        return False, f"HTTP {e.code} ({e.reason}){detail}"
    except Exception as e:
        return False, f"{type(e).__name__}: {e}"


def run_canaries(values: dict[str, str], zotero_dir: str) -> None:
    print("\n=== Running 1-Request Canaries (No Secrets Printed) ===")
    zpath = Path(zotero_dir)
    z_ok = (zpath / "zotero.sqlite").is_file() and (zpath / "storage").is_dir()
    print(f"  [ZOTERO_DATA_DIR]            {'OK' if z_ok else 'MISSING'} ({zpath})")

    oa_key = values.get("SPRINGER_OPENACCESS_API_KEY", "")
    if oa_key:
        q = urllib.parse.quote("keyword:microbiome")
        ok, msg = _probe(
            f"https://api.springernature.com/openaccess/jats?q={q}&p=1&s=1&api_key={urllib.parse.quote(oa_key)}"
        )
        print(f"  [SPRINGER_OPENACCESS_API]    {'OK' if ok else 'WARN'} — {msg}")

    meta_key = values.get("SPRINGER_META_API_KEY", "")
    if meta_key:
        q = urllib.parse.quote("keyword:microbiome")
        ok, msg = _probe(
            f"https://api.springernature.com/meta/v2/json?q={q}&p=1&s=1&api_key={urllib.parse.quote(meta_key)}"
        )
        print(f"  [SPRINGER_META_API]          {'OK' if ok else 'WARN'} — {msg}")

    ls_key = values.get("SPRINGER_LIFESCIENCE_API_KEY", "") or meta_key
    if ls_key:
        q_ls = urllib.parse.quote("keyword:biology")
        ok_ls, msg_ls = _probe(
            f"https://api.springernature.com/meta/v2/json?q={q_ls}&p=1&s=1&api_key={urllib.parse.quote(ls_key)}"
        )
        if not ok_ls and meta_key and ls_key != meta_key:
            ok_ls, msg_ls = _probe(
                f"https://api.springernature.com/meta/v2/json?q={q_ls}&p=1&s=1&api_key={urllib.parse.quote(meta_key)}"
            )
            if ok_ls:
                msg_ls += " (via SPRINGER_META_API_KEY on /meta/v2/json)"
                values["SPRINGER_LIFESCIENCE_API_KEY"] = meta_key
                write_env_file(values, zotero_dir)
        print(f"  [SPRINGER_LIFESCIENCE_API]   {'OK' if ok_ls else 'WARN'} — {msg_ls}")

    core_key = values.get("CORE_API_KEY", "")
    if core_key:
        q = urllib.parse.quote('doi:"10.1038/s41564-024-01641-6"')
        ok, msg = _probe(
            f"https://api.core.ac.uk/v3/search/works?q={q}&limit=1",
            headers={"Authorization": f"Bearer {core_key}"},
        )
        print(f"  [CORE_API_KEY]               {'OK' if ok else 'WARN'} — {msg}")

    wiley_tok = values.get("WILEY_TDM_TOKEN", "")
    if wiley_tok:
        enc_doi = urllib.parse.quote("10.1111/1462-2920.16600", safe="")
        ok, msg = _probe(
            f"https://api.wiley.com/onlinelibrary/tdm/v1/articles/{enc_doi}",
            headers={
                "Wiley-TDM-Client-Token": wiley_tok,
                "Accept": "application/pdf",
            },
        )
        print(f"  [WILEY_TDM_TOKEN]            {'OK' if ok else 'WARN'} — {msg}")

    cas_key = values.get("CAS_COMMON_CHEMISTRY_API_KEY", "") or values.get("CAS_API_KEY", "")
    if cas_key:
        ok, msg = _probe(
            "https://commonchemistry.cas.org/direct-api/detail?cas_rn=50-00-0",
            headers={
                "accept": "application/json",
                "x-origin": "https://commonchemistry.cas.org/api-overview",
                "X-API-KEY": cas_key,
            },
        )
        print(f"  [CAS_COMMON_CHEMISTRY_API]   {'OK' if ok else 'WARN'} — {msg}")
    else:
        print("  [CAS_COMMON_CHEMISTRY_API]   SKIP (unset)")

    elsevier_key = values.get("ELSEVIER_API_KEY", "")
    if elsevier_key:
        ok, msg = verify_elsevier_canary(elsevier_key)
        print(f"  [ELSEVIER_API_KEY]           {'OK' if ok else 'WARN'} — {msg}")
    else:
        print("  [ELSEVIER_API_KEY]           SKIP (unset)")


def verify_elsevier_canary(elsevier_key: str) -> tuple[bool, str]:
    """Run a 1-request Elsevier Article Retrieval API canary without exposing the key."""
    if not elsevier_key:
        return False, "ELSEVIER_API_KEY is unset"
    enc_doi = urllib.parse.quote("10.1016/j.cell.2019.01.029", safe="/")
    return _probe(
        f"https://api.elsevier.com/content/article/doi/{enc_doi}?httpAccept=text/xml",
        headers={
            "X-ELS-APIKey": elsevier_key,
            "Accept": "text/xml",
        },
    )


def ingest_acs_tdm_feed(feed_dir: Path, master_tsv: Path | None = None) -> dict[str, int]:
    """Scan an ACS TDM XML/PDF feed directory and match files against 10.1021/* DOIs."""
    if not feed_dir.is_dir():
        raise FileNotFoundError(f"ACS TDM feed directory does not exist: {feed_dir}")
    doi_re = re.compile(r"10\.1021/[A-Za-z0-9._;()/-]+", re.IGNORECASE)
    known_dois: set[str] = set()
    if master_tsv is not None and master_tsv.is_file():
        for line in master_tsv.read_text(encoding="utf-8", errors="ignore").splitlines()[1:]:
            parts = line.split("\t")
            if parts and parts[0].strip():
                known_dois.add(parts[0].strip().lower())

    xml_files = 0
    pdf_files = 0
    matched_dois: set[str] = set()
    for p in sorted(feed_dir.rglob("*")):
        if not p.is_file():
            continue
        suf = p.suffix.lower()
        if suf in {".xml", ".nxml"}:
            xml_files += 1
        elif suf == ".pdf":
            pdf_files += 1
        else:
            continue
        stem_norm = p.stem.replace("_", "/")
        for candidate in (stem_norm, p.read_text(encoding="utf-8", errors="ignore")[:8192] if suf in {".xml", ".nxml"} else ""):
            for m in doi_re.finditer(candidate):
                d = m.group(0).rstrip(".,;:)]}>'\"`*").lower()
                if not known_dois or d in known_dois:
                    matched_dois.add(d)
    return {
        "xml_files": xml_files,
        "pdf_files": pdf_files,
        "matched_dois": len(matched_dois),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check-only",
        action="store_true",
        help="Check ~/.config/lbnl-tdm.env and run canaries without prompting",
    )
    parser.add_argument(
        "--sync-rc",
        action="store_true",
        help="Ensure ~/.zshenv, ~/.zshrc, ~/.bashrc, and ~/.bash_profile source ~/.config/lbnl-tdm.env",
    )
    parser.add_argument(
        "--no-canary",
        action="store_true",
        help="Skip live 1-request API canary checks",
    )
    parser.add_argument(
        "--verify-elsevier",
        action="store_true",
        help="Verify ELSEVIER_API_KEY via a 1-request ScienceDirect TDM canary",
    )
    parser.add_argument(
        "--ingest-acs-tdm-feed",
        type=Path,
        default=None,
        help="Validate and index an ACS TDM XML/PDF feed directory against acs_dois_master.tsv",
    )
    args = parser.parse_args()

    existing = load_existing(ENV_FILE)
    zotero_dir = existing.get("ZOTERO_DATA_DIR") or str(HOME / "Zotero")

    if args.ingest_acs_tdm_feed is not None:
        default_master = (
            HOME
            / "Documents"
            / "VIMSS"
            / "ontology"
            / "Mechs"
            / "XMechBay"
            / ".temp"
            / "mech-chemicals-and-acs-dois"
            / "acs_dois_master.tsv"
        )
        stats = ingest_acs_tdm_feed(args.ingest_acs_tdm_feed, default_master)
        print(f"ACS TDM feed summary: {stats}")
        return 0

    if args.verify_elsevier:
        ok, msg = verify_elsevier_canary(existing.get("ELSEVIER_API_KEY", ""))
        print(f"[ELSEVIER_API_KEY] {'OK' if ok else 'WARN'} — {msg}")
        return 0 if ok else 1

    if not args.check_only:
        print("=== LBNL Library, TDM & CAS API Key Setup ===")
        print("Paste each key at the prompt (input is hidden so keys never appear on screen).")
        print("Press Enter on any prompt to keep its existing value.\n")

        for env_name, label, _ in KEY_SPECS:
            cur = existing.get(env_name, "")
            status = mask(cur)
            prompt = f"  {label} [{env_name}: {status}]: "
            entered = getpass.getpass(prompt).strip()
            if len(entered) >= 2 and entered[0] == entered[-1] and entered[0] in ('"', "'"):
                entered = entered[1:-1]
            if entered:
                existing[env_name] = entered

        env_bak = write_env_file(existing, zotero_dir)
        print(f"\nSaved {ENV_FILE} (permissions 0600)" + (f", backup: {env_bak}" if env_bak else ""))
        sync_all_shell_rcs()
    elif args.sync_rc:
        sync_all_shell_rcs()

    print("\n=== Configured Variables Summary ===")
    print(f"  ZOTERO_DATA_DIR              = {zotero_dir}")
    for env_name, _, note in KEY_SPECS:
        print(f"  {env_name:<28} = {mask(existing.get(env_name, ''))}  ({note})")

    if not args.no_canary:
        run_canaries(existing, zotero_dir)

    print("\nTo load the keys into your current shell immediately, run:")
    print("  source ~/.config/lbnl-tdm.env")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
